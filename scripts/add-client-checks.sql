CREATE TABLE IF NOT EXISTS public.client_checks (
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  client_name text NOT NULL,
  check_date date NOT NULL,
  amount numeric NOT NULL CHECK (amount > 0::numeric),
  bank text,
  check_number text,
  notes text,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  CONSTRAINT client_checks_pkey PRIMARY KEY (id)
);

CREATE INDEX IF NOT EXISTS idx_client_checks_check_date
  ON public.client_checks (check_date DESC);

ALTER TABLE public.client_checks ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public'
      AND tablename = 'client_checks'
      AND policyname = 'Enable read access for all users'
  ) THEN
    CREATE POLICY "Enable read access for all users"
      ON public.client_checks
      FOR SELECT
      USING (true);
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public'
      AND tablename = 'client_checks'
      AND policyname = 'Enable insert for authenticated users only'
  ) THEN
    CREATE POLICY "Enable insert for authenticated users only"
      ON public.client_checks
      FOR INSERT
      WITH CHECK (true);
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public'
      AND tablename = 'client_checks'
      AND policyname = 'Enable update for authenticated users only'
  ) THEN
    CREATE POLICY "Enable update for authenticated users only"
      ON public.client_checks
      FOR UPDATE
      USING (true);
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public'
      AND tablename = 'client_checks'
      AND policyname = 'Enable delete for authenticated users only'
  ) THEN
    CREATE POLICY "Enable delete for authenticated users only"
      ON public.client_checks
      FOR DELETE
      USING (true);
  END IF;
END $$;
